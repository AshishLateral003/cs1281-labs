# The raw log line straight from the machine's text output
raw_line = "  PART-A01 |  25.04   | Day  "

# Why a list: split() creates an ordered sequence of substrings that we can access by index position.
fields = raw_line.split("|")

# String parsing: strip() removes the messy whitespace
part_code = fields[0].strip()
diameter = float(fields[1].strip())
shift = fields[2].strip()

print(f"Part Code: {part_code}")
print(f"Diameter: {diameter}")
print(f"Shift: {shift}")

# Proving the float cast worked (you cannot do math on a string)
print(f"Tool offset calibration (dia + 0.01): {diameter + 0.01} mm")

# Why a list: A shift log is chronological and contains duplicate data that we must preserve exactly in order.
shift_log = [
    "PART-101 | 25.01 | Day",
    "  PART-102|24.93 |Day ",
    "PART-103 |25.05| Day",
    " PART-104 |  25.00  | Day",
    "PART-105|25.10|Day",
    "PART-106 |24.99| Day",
    "PART-107| 25.01 | Day",
    "PART-108 | 24.95 |Day",
    "PART-109| 24.89 | Day",
    "PART-110|  25.02 |Day"
]

# Why a list: We need to keep every single measurement (including duplicates) to calculate an accurate average and count.
diameters = []

for line in shift_log:
    # Why a list: Temporary indexed storage for the three extracted text fields.
    fields = line.split("|")
    dia = float(fields[1].strip())
    diameters.append(dia)

count = len(diameters)
avg = sum(diameters) / count
min_dia = min(diameters)
max_dia = max(diameters)

print(f"Batch Count: {count}")
print(f"Average Dia: {avg:.3f} mm")
print(f"Max Dia: {max_dia} mm | Min Dia: {min_dia} mm")

# (Using the same shift_log list from IT10 above)

# Why a list: We need all valid measurements to calculate the specific average of just the accepted parts.
accepted_dia = []
# Why a list: Tracks the volume of oversized parts awaiting manual machining.
rework_dia = []
# Why a list: The supervisor needs the exact ordered sequence of part codes that failed, not just their measurements.
scrap_codes = []

for line in shift_log:
    # Why a list: Temporary indexed string parsing array.
    fields = line.split("|")
    part_code = fields[0].strip()
    dia = float(fields[1].strip())

    if 24.95 <= dia <= 25.05:
        accepted_dia.append(dia)
    elif dia > 25.05:
        rework_dia.append(dia)
    else:
        scrap_codes.append(part_code)

if accepted_dia:
    acc_avg = sum(accepted_dia) / len(accepted_dia)
else:
    acc_avg = 0.0

print(f"--- SHIFT REPORT ---")
print(f"ACCEPTED: {len(accepted_dia)} (Avg: {acc_avg:.3f} mm)")
print(f"REWORK: {len(rework_dia)}")
print(f"SCRAP: {len(scrap_codes)}")
print(f"Scrapped Part Codes for Supervisor: {', '.join(scrap_codes)}")

# Why a list: Chronological log of the day shift's production run.
day_log = ["A01|25.00", "A02|24.93", "A03|25.10", "A04|24.99"]
# Why a list: Chronological log of the night shift's production run.
night_log = ["A02|24.91", "B01|25.01", "B02|25.00", "A03|24.92"]

def parse_shift(log):
    accepted_count = 0
    # Why a set: We only care *if* a part code failed to find machine patterns, not how many times it failed.
    scrap_set = set()

    for line in log:
        # Why a list: Temporary indexed string parsing array.
        fields = line.split("|")
        code = fields[0].strip()
        dia = float(fields[1].strip())

        if 24.95 <= dia <= 25.05:
            accepted_count += 1
        else:
            scrap_set.add(code)

    yield_rate = (accepted_count / len(log)) * 100
    # Why a tuple: A function returning multiple pieces of rigid, unchangeable data must use a tuple.
    return (yield_rate, scrap_set)

day_yield, day_scrap = parse_shift(day_log)
night_yield, night_scrap = parse_shift(night_log)

print(f"Day Shift Yield: {day_yield}%")
print(f"Night Shift Yield: {night_yield}%")

# Set Mathematics (The true power of sets)
common_scrap = day_scrap.intersection(night_scrap)
day_only_scrap = day_scrap.difference(night_scrap)
night_only_scrap = night_scrap.difference(day_scrap)

print(f"\n--- SCRAP ANALYSIS ---")
print(f"Parts scrapped on BOTH shifts (Check machine tooling): {common_scrap}")
print(f"Parts scrapped ONLY on Day Shift (Check operator setup): {day_only_scrap}")
print(f"Parts scrapped ONLY on Night Shift (Check operator setup): {night_only_scrap}")