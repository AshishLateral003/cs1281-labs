class StampingPress:
    # 1. The __init__ constructor (The blueprint)
    def __init__(self, model_name, max_tonnage):
        self.model = model_name         # Attribute 1
        self.max_tonnage = max_tonnage  # Attribute 2 (Limit/Rating)
        self.parts_stamped = 0          # Attribute 3 (State counter)

    # 2. The __str__ method (The physical nameplate)
    def __str__(self):
        return f"[{self.model} Press | Rating: {self.max_tonnage}T]"

    # 3. The working method (The machine in action)
    def cycle(self):
        print(f"{self.model} cycling... CLUNK!")
        self.parts_stamped += 1

# --- COMMISSIONING & TESTING ---
press_A = StampingPress("Alpha-100", 50)
press_B = StampingPress("Titan-X", 250)

print(press_A)
print(press_B)

# Prove states are independent by running Press A three times and Press B once
press_A.cycle()
press_A.cycle()
press_A.cycle()
press_B.cycle()

print(f"\n{press_A.model} Parts Count: {press_A.parts_stamped}")
print(f"{press_B.model} Parts Count: {press_B.parts_stamped}")

class GuardedLathe:
    def __init__(self, model, max_rpm):
        self.model = model
        self.__max_rpm = max_rpm       # PRIVATE state (Guarded)
        self.__parts_machined = 0      # PRIVATE state (Guarded)

    def __str__(self):
        return f"{self.model} CNC Lathe"

    def machine_part(self, programmed_rpm):
        # The Validating Guard
        if programmed_rpm > self.__max_rpm:
            print(f"FAULT: {programmed_rpm} RPM exceeds {self.model}'s {self.__max_rpm} RPM limit. Spindle locked.")
        else:
            self.__parts_machined += 1
            print(f"Machining at {programmed_rpm} RPM... Success.")

    # The Getter (Read-only access to private state)
    def status(self):
        return self.__parts_machined

# --- TESTING THE GUARDS ---
lathe1 = GuardedLathe("Haas ST-20", 4000)
lathe1.machine_part(3500)  # Safe
lathe1.machine_part(4500)  # Trips the guard
print(f"Shift Output: {lathe1.status()} parts")

import random

class QualityScanner:
    def __init__(self, station_id):
        self.station_id = station_id
        # Private operational state
        self.__accepted = 0
        self.__rejected = 0

    def inspect(self, diameter):
        if 24.95 <= diameter <= 25.05:
            self.__accepted += 1
            return "ACCEPT"
        else:
            self.__rejected += 1
            return "REJECT"

    def status(self):
        total = self.__accepted + self.__rejected
        return f"Station {self.station_id} | Total: {total} | Accept: {self.__accepted} | Reject: {self.__rejected}"

# --- RUNNING THE BATCH ---
scanner = QualityScanner("QC-Line-1")

print("Processing batch of 10 parts...\n")
for i in range(10):
    dia = round(random.uniform(24.90, 25.10), 2)
    result = scanner.inspect(dia)
    print(f"Part {i+1}: {dia}mm -> {result}")

print("\n--- SHIFT REPORT ---")
print(scanner.status())

class CncMachine:
    def __init__(self, name):
        self.name = name
        self.__parts_run = 0
        self.__busy = False

    def is_free(self):
        import random
        # Simulate machine availability (80% chance it is free to take a job)
        self.__busy = random.random() > 0.8
        return not self.__busy

    def process_job(self, job_id):
        self.__parts_run += 1

    def get_count(self):
        return self.__parts_run

