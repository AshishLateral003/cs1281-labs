print("Terminal online.")
name = input("Operator name: ")
print(f"Welcome to the shop floor, {name}.")

accepted = 0
rework = 0
scrap = 0

print("Nominal: 25.00mm. Accept: ±0.05. Rework: >25.05. Scrap: <24.95.")

for i in range(10):
    diameter = float(input(f"Enter diameter for part {i+1}: "))

    if 24.95 <= diameter <= 25.05:
        print("--> ACCEPT")
        accepted += 1
    elif diameter > 25.05:
        # Oversized outer diameters can be machined down
        print("--> REWORK")
        rework += 1
    else:
        # Undersized outer diameters are lost material
        print("--> SCRAP")
        scrap += 1

print(f"\nBatch complete: {accepted} ACCEPT, {rework} REWORK, {scrap} SCRAP")

total_parts = int(input("Total parts to pack: "))
box_size = int(input("Parts per box: "))

full_boxes = total_parts // box_size
loose_parts = total_parts % box_size

print(f"Full boxes: {full_boxes}")
print(f"Loose parts: {loose_parts}")

# The Audit Line
audit_check = (full_boxes * box_size + loose_parts) == total_parts
print(f"Audit (boxes*size + loose == total): {audit_check}")

accepted = 0
rework = 0
scrap = 0
box_capacity = 4

print("--- SHIFT BATCH INSPECTION ---")
for i in range(10):
    diameter = float(input(f"Part {i+1} diameter: "))

    if 24.95 <= diameter <= 25.05:
        accepted += 1
    elif diameter > 25.05:
        rework += 1
    else:
        scrap += 1

print("\n--- PALLET PACKING ---")
full_boxes = accepted // box_capacity
loose_parts = accepted % box_capacity

print("\n--- END OF SHIFT REPORT ---")
print(f"Total Inspected: 10")
print(f"Quality Bins: {accepted} ACCEPT | {rework} REWORK | {scrap} SCRAP")
print(f"Shipping: {full_boxes} full boxes packed. {loose_parts} accepted parts left loose.")