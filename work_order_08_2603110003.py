# 1. Define the Custom Domain Exception
class SpecViolation(Exception):
    """Raised when a commanded dimension exceeds physical machine limits."""
    pass

# 2. The Machine Class
class CncMachine:
    def __init__(self, name, max_tool_travel):
        self.name = name
        self.max_travel = max_tool_travel
        self.parts_run = 0

    def process(self, diameter):
        # The internal guard raising our custom exception
        if diameter > self.max_travel:
            raise SpecViolation(f"Diameter {diameter}mm exceeds {self.name}'s max travel of {self.max_travel}mm.")

        self.parts_run += 1
        return True

# 3. The Fleet Driver Program
lathe = CncMachine("Haas-ST", 50.0)
job_diameters = [25.0, 30.5, 99.9, 24.8]  # 99.9 is a catastrophic physical crash

print("--- RUNNING FLEET JOBS ---")
for dia in job_diameters:
    try:
        lathe.process(dia)
        print(f"Machining part (Dia: {dia}mm) ... Success")
    except SpecViolation as e:
        # We catch the exact domain error so the loop keeps running for the next part
        print(f"JOB REJECTED: {e}")

print(f"\nTotal successful parts: {lathe.parts_run}")

