# The Batch Processor
plant_total_valid = 0
plant_total_rejects = 0

print("--- INITIATING BATCH PROCESSING ---")

# Glob finds every file ending in .txt in the data folder
target_files = glob.glob(os.path.join(data_dir, "*.txt"))

# Open the history file in APPEND ("a") mode
with open(history_path, "a") as history_file:
    # Write header if file is empty (new system)
    if os.path.getsize(history_path) == 0:
        history_file.write("Timestamp,File_Processed,Valid_Records,Rejected_Records\n")

    for file_path in target_files:
        valid_count = 0
        reject_count = 0

        # Read the file
        with open(file_path, "r") as f:
            for line in f:
                if not line.strip(): continue

                try:
                    dia = float(line.split("|")[1].strip())
                    valid_count += 1
                except (IndexError, ValueError):
                    reject_count += 1

        # Update plant totals
        plant_total_valid += valid_count
        plant_total_rejects += reject_count

        # Log to the running history file
        timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        file_name = os.path.basename(file_path)
        history_file.write(f"{timestamp},{file_name},{valid_count},{reject_count}\n")

        print(f"Processed {file_name}: {valid_count} Valid | {reject_count} Rejects")

print("\n--- PLANT SUMMARY ---")
print(f"Total Output: {plant_total_valid} parts across {len(target_files)} shifts.")
print(f"System Audit Log updated: {history_path}")