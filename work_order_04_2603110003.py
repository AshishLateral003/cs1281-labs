import random

print("Machine Modes: 'halt' (E-Stop on scrap) | 'skip' (log and continue)")
mode = input("Enter operator mode: ").strip().lower()

inspected = 0

for i in range(50):
    diameter = round(random.uniform(24.90, 25.10), 2)
    inspected += 1

    # Check for Scrap first (the critical failure)
    if diameter < 24.95:
        if mode == "halt":
            print(f"Part {i+1}: {diameter} mm --> SCRAP. Halting production line!")
            break  # Emergency Stop
        else:
            print(f"Part {i+1}: {diameter} mm --> SCRAP. Skipping...")
            continue # Bypass downstream logic, move to next part

    # Check for Accept/Rework if it wasn't Scrap
    if diameter <= 25.05:
        print(f"Part {i+1}: {diameter} mm --> ACCEPT")
    else:
        print(f"Part {i+1}: {diameter} mm --> REWORK")

print(f"\nLine stopped. Total parts inspected: {inspected}")

import random

consecutive_accepts = 0
total_parts = 0
safety_cap = 500

print("Warming up machine. Target: 5 consecutive ACCEPTs to stabilize process.")

while consecutive_accepts < 5:
    # 1. The Safety Cap
    if total_parts >= safety_cap:
        print("\n[!] ALARM: Safety cap reached (500 parts). Tooling is likely broken. Shutting down.")
        break

    total_parts += 1
    diameter = round(random.uniform(24.90, 25.10), 2)

    # 2. Quality Check
    if 24.95 <= diameter <= 25.05:
        consecutive_accepts += 1
        print(f"Part {total_parts}: {diameter} mm --> ACCEPT (Streak: {consecutive_accepts}/5)")
    else:
        # Reset the streak to zero if a bad part comes off the line
        consecutive_accepts = 0
        print(f"Part {total_parts}: {diameter} mm --> REJECT (Streak reset to 0)")

if consecutive_accepts == 5:
    print(f"\nProcess Stabilized! It took {total_parts} total parts to dial in the machine.")

