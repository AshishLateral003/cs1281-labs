def inspect(dia):
    """Takes a diameter float; returns 'ACCEPT', 'REWORK', or 'SCRAP'."""
    if 24.95 <= dia <= 25.05:
        return "ACCEPT"
    elif dia > 25.05:
        return "REWORK"
    else:
        return "SCRAP"

def tally(labels):
    """Takes a list of bin labels; returns a dictionary of their counts."""
    counts = {"ACCEPT": 0, "REWORK": 0, "SCRAP": 0}
    for label in labels:
        if label in counts:
            counts[label] += 1
    return counts

def report(shift, counts):
    """Takes a shift name and counts dictionary; returns a formatted shift report string."""
    return f"Shift: {shift} | ACCEPT: {counts.get('ACCEPT', 0)} | REWORK: {counts.get('REWORK', 0)} | SCRAP: {counts.get('SCRAP', 0)}"

