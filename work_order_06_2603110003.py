# --- THE REFACTORED PIPELINE ---
# Raw data from the machine log
diameters = [25.01, 24.93, 25.10, 25.00, 24.99, 25.05, 24.90]

# 1. Process all parts through the inspection jig
bin_labels = []
for dia in diameters:
    bin_labels.append(inspect(dia))

# 2. Feed the labels into the tally jig
final_counts = tally(bin_labels)

# 3. Feed the tally into the reporting jig
final_output = report("Night", final_counts)

print(final_output)

# Our dictionary acting as the shop's part catalogue
catalogue = {
    "PART-A01": 25.01,
    "PART-A02": 24.93,
    "PART-B01": 25.10,
    "PART-B02": 25.00
}

def lookup(catalogue, code):
    """Takes a catalogue dictionary and part code; returns the diameter or a safe default error."""
    # .get() prevents the program from crashing if the operator types a typo.
    return catalogue.get(code, "Error: Part code not found in system")

def scrap_codes(catalogue):
    """Takes a catalogue dictionary; returns a set of part codes that measure as SCRAP."""
    scrap_set = set()
    # .items() lets us loop over both the code (key) and the dia (value) simultaneously
    for code, dia in catalogue.items():
        if inspect(dia) == "SCRAP":
            scrap_set.add(code)
    return scrap_set

