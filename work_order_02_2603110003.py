parts_produced = 0

for i in range(5):
    print("Machine cycling...")
    parts_produced = parts_produced + 1

print(f"Batch complete. Total parts: {parts_produced}")

operator_name = input("Enter operator name: ")
print(f"Welcome to the station, {operator_name}.")

batch_size = input("How many parts are we producing today? ")
batch_size = int(batch_size)

print("Starting production...")
for i in range(batch_size):
    print(f"Stamping part number {i + 1}...")

print("Nominal specification: 25.00 mm ± 0.05 mm")
raw_measurement = input("Enter measured diameter: ")
diameter = float(raw_measurement)

if diameter >= 24.95 and diameter <= 25.05:
    print("ACCEPT: Part is within tolerance (GO).")
elif diameter < 24.95:
    print("REJECT: Part is undersized (NO-GO).")
else:
    print("REJECT: Part is oversized (NO-GO).")

import random

accepted = 0
rejected = 0

print("Initializing automated batch inspection (10 parts)...")

for i in range(10):
    # Simulate a part between 24.90 and 25.10
    diameter = round(random.uniform(24.90, 25.10), 2)

    if 24.95 <= diameter <= 25.05:
        print(f"Part {i+1}: {diameter}mm - ACCEPT")
        accepted += 1
    else:
        print(f"Part {i+1}: {diameter}mm - REJECT")
        rejected += 1

print(f"10 inspected · {accepted} accepted · {rejected} rejected")